using UnityEditor;
using UnityEngine;
using System.IO;
using System.Linq;
using System;
using UnityEngine.Tilemaps;

public class ConvertToRuleTiles
{
    [MenuItem("Tools/Sunny Land/Convert Auto Tiles -> RuleTiles (if available)")]
    public static void Convert()
    {
        // Load mapping
        string mappingPath = "Assets/Tiles/AutoGenerated/mapping.json";
        if (!File.Exists(mappingPath))
        {
            EditorUtility.DisplayDialog("Mapping not found", "Please run Generate Auto Tiles first (Tools -> Sunny Land -> Generate Auto Tiles).", "OK");
            return;
        }

        string json = File.ReadAllText(mappingPath);
        var mappingList = JsonUtility.FromJson<MappingList>(json);
        if (mappingList == null || mappingList.entries == null || mappingList.entries.Length == 0)
        {
            EditorUtility.DisplayDialog("Mapping invalid", "mapping.json is empty or invalid.", "OK");
            return;
        }

        // Try find RuleTile type via reflection
        Type ruleTileType = null;
        foreach (var asm in AppDomain.CurrentDomain.GetAssemblies())
        {
            ruleTileType = asm.GetType("UnityEngine.Tilemaps.RuleTile");
            if (ruleTileType != null) break;
        }

        if (ruleTileType == null)
        {
            EditorUtility.DisplayDialog("RuleTile not found", "RuleTile type not found in loaded assemblies. Install 2D Tilemap Extras and restart Unity, then run this again.", "OK");
            return;
        }

        string outputRoot = "Assets/Tiles/RuleTiles";
        if (!Directory.Exists(outputRoot)) Directory.CreateDirectory(outputRoot);

        int created = 0;
        foreach (var e in mappingList.entries)
        {
            string spritePath = e.sprite;
            string group = e.group;
            Sprite spr = AssetDatabase.LoadAssetAtPath<Sprite>(spritePath);
            if (spr == null) continue;

            // Create a RuleTile instance via reflection
            UnityEngine.Object rt = ScriptableObject.CreateInstance(ruleTileType);
            // Try set the m_DefaultSprite or equivalent field via reflection (implementation detail varies)
            var field = ruleTileType.GetField("m_DefaultSprite", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance);
            if (field != null) field.SetValue(rt, spr);
            else
            {
                // fallback: try property
                var prop = ruleTileType.GetProperty("defaultSprite");
                if (prop != null && prop.CanWrite) prop.SetValue(rt, spr, null);
            }

            string fileName = Path.GetFileNameWithoutExtension(spritePath) + "_Rule.asset";
            string assetPath = Path.Combine(outputRoot, group + "_" + fileName).Replace("\\", "/");
            AssetDatabase.CreateAsset(rt, assetPath);
            created++;
        }

        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();
        EditorUtility.DisplayDialog("Conversion complete", $"Created {created} RuleTile assets in {outputRoot}. You may need to open Tile Palette to inspect and adjust rules.", "OK");
    }

    [System.Serializable]
    class MappingEntry { public string sprite; public string group; }
    [System.Serializable]
    class MappingList { public MappingEntry[] entries; }
}
