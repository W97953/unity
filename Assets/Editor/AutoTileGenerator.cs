using UnityEditor;
using UnityEngine;
using UnityEngine.Tilemaps;
using System.IO;
using System.Linq;
using System.Collections.Generic;

public class AutoTileGenerator
{
    // 默认关键词分组（小写）
    static readonly Dictionary<string, string[]> groupKeywords = new Dictionary<string, string[]>()
    {
        { "ground", new[] { "grass","dirt","soil","ground" } },
        { "water",  new[] { "water","lake","sea","river","pond" } },
        { "lava",   new[] { "lava","magma" } },
        { "wall",   new[] { "wall","rock","stone","cliff" } },
        { "decor",  new[] { "tree","bush","flower","plant","deco" } },
        { "items",  new[] { "gem","coin","collectible","pickup" } }
    };

    [MenuItem("Tools/Sunny Land/Generate Auto Tiles")]
    public static void Generate()
    {
        string artRoot = "Assets/Art/SugerWorld";
        if (!AssetDatabase.IsValidFolder(artRoot))
        {
            EditorUtility.DisplayDialog("Art folder not found", $"Could not find {artRoot}. Please extract SugerWorld.zip to Assets/Art/SugerWorld first.", "OK");
            return;
        }

        string outputRoot = "Assets/Tiles/AutoGenerated";
        if (!Directory.Exists(outputRoot)) Directory.CreateDirectory(outputRoot);

        // Find all sprites under artRoot
        string[] guids = AssetDatabase.FindAssets("t:Sprite", new[] { artRoot });
        if (guids == null || guids.Length == 0)
        {
            EditorUtility.DisplayDialog("No sprites found", $"No sprites found under {artRoot}.", "OK");
            return;
        }

        var mapping = new Dictionary<string, string>(); // sprite asset path -> group

        foreach (var g in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(g);
            string fileName = Path.GetFileNameWithoutExtension(path).ToLowerInvariant();

            // determine group by keywords
            string chosenGroup = "decor"; // fallback
            foreach (var kv in groupKeywords)
            {
                foreach (var kw in kv.Value)
                {
                    if (fileName.Contains(kw))
                    {
                        chosenGroup = kv.Key;
                        goto found;
                    }
                }
            }
        found:
            mapping[path] = chosenGroup;

            // create group folder
            string groupFolder = Path.Combine(outputRoot, chosenGroup);
            if (!Directory.Exists(groupFolder)) Directory.CreateDirectory(groupFolder);

            // create a Tile asset for this sprite (if not exists)
            string tileName = Path.GetFileNameWithoutExtension(path) + ".asset";
            string tileAssetPath = Path.Combine(groupFolder, tileName).Replace("\\", "/");
            if (!File.Exists(tileAssetPath))
            {
                Sprite sprite = AssetDatabase.LoadAssetAtPath<Sprite>(path);
                Tile tile = ScriptableObject.CreateInstance<Tile>();
                tile.sprite = sprite;
                AssetDatabase.CreateAsset(tile, tileAssetPath);
            }
        }

        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();

        // write mapping.json for later conversions
        string jsonPath = Path.Combine(outputRoot, "mapping.json");
        var entries = mapping.Select(kv => new MappingEntry { sprite = kv.Key, group = kv.Value }).ToArray();
        string json = JsonUtility.ToJson(new MappingList { entries = entries }, true);
        File.WriteAllText(jsonPath, json);
        AssetDatabase.ImportAsset(jsonPath);

        EditorUtility.DisplayDialog("Auto Tiles Generated", $"Generated {mapping.Count} tiles in {outputRoot}. Mapping saved to {jsonPath}.", "OK");
    }

    [System.Serializable]
    class MappingEntry { public string sprite; public string group; }

    [System.Serializable]
    class MappingList { public MappingEntry[] entries; }
}
